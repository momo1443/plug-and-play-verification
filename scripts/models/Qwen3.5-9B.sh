#!/usr/bin/env bash
set -euo pipefail

# The task flow and verifier are shared with 4B; model adaptation uses LoRA.
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$PROJECT_DIR/scripts/common/pnp.sh"
DATASET="${1:?Usage: Qwen3.5-9B.sh DATASET [HYDRA_OVERRIDES...] }"
shift
pnp_model_path "$DATASET" Qwen3.5-9B
export PYTHON_BIN="${PYTHON_BIN:-$(command -v python)}"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}"
export AGENT_R1_MODEL_SCALE="${AGENT_R1_MODEL_SCALE:-9b}"
export AGENT_R1_LORA_RANK="${AGENT_R1_LORA_RANK:-64}"

case "$DATASET" in
    hotpotqa)
        # Preserve the previous 9B QA memory and checkpoint profile.
        IFS=',' read -r -a _VISIBLE_GPUS <<<"$CUDA_VISIBLE_DEVICES"
        export HOTPOTQA_NUM_GPUS="${HOTPOTQA_NUM_GPUS:-${#_VISIBLE_GPUS[@]}}"
        export HOTPOTQA_RUN_MODE="${HOTPOTQA_RUN_MODE:-main}"
        export HOTPOTQA_TRAIN_BATCH_SIZE="${HOTPOTQA_TRAIN_BATCH_SIZE:-8}"
        export HOTPOTQA_ROLLOUT_N="${HOTPOTQA_ROLLOUT_N:-4}"
        export HOTPOTQA_GRPO_MICRO_BATCH_SIZE="${HOTPOTQA_GRPO_MICRO_BATCH_SIZE:-1}"
        export HOTPOTQA_VAL_BATCH_SIZE="${HOTPOTQA_VAL_BATCH_SIZE:-4}"
        export HOTPOTQA_VLLM_GPU_MEMORY_UTILIZATION="${HOTPOTQA_VLLM_GPU_MEMORY_UTILIZATION:-0.25}"
        export HOTPOTQA_VLLM_MAX_MODEL_LEN="${HOTPOTQA_VLLM_MAX_MODEL_LEN:-12288}"
        export HOTPOTQA_VLLM_MAX_NUM_BATCHED_TOKENS="${HOTPOTQA_VLLM_MAX_NUM_BATCHED_TOKENS:-12288}"
        export HOTPOTQA_VLLM_MAX_NUM_SEQS="${HOTPOTQA_VLLM_MAX_NUM_SEQS:-32}"
        export HOTPOTQA_ACTOR_USE_DYNAMIC_BSZ="${HOTPOTQA_ACTOR_USE_DYNAMIC_BSZ:-true}"
        export HOTPOTQA_ACTOR_MAX_TOKEN_LEN_PER_GPU="${HOTPOTQA_ACTOR_MAX_TOKEN_LEN_PER_GPU:-8192}"
        export HOTPOTQA_ACTOR_PARAM_OFFLOAD="${HOTPOTQA_ACTOR_PARAM_OFFLOAD:-true}"
        export HOTPOTQA_ACTOR_OPTIMIZER_OFFLOAD="${HOTPOTQA_ACTOR_OPTIMIZER_OFFLOAD:-true}"
        export HOTPOTQA_SAVE_FREQ="${HOTPOTQA_SAVE_FREQ:-50}"
        export HOTPOTQA_MAX_ACTOR_CKPT_TO_KEEP="${HOTPOTQA_MAX_ACTOR_CKPT_TO_KEEP:-2}"
        ;;
    taco)
        # Preserve the previous 9B code-generation memory profile.
        export TACO_A9_TENSOR_PARALLEL_SIZE="${TACO_A9_TENSOR_PARALLEL_SIZE:-8}"
        export TACO_A9_TRAIN_BATCH_SIZE="${TACO_A9_TRAIN_BATCH_SIZE:-8}"
        export TACO_A9_ROLLOUT_N="${TACO_A9_ROLLOUT_N:-4}"
        export TACO_A9_MAX_PROMPT_LENGTH="${TACO_A9_MAX_PROMPT_LENGTH:-8192}"
        export TACO_A9_MAX_RESPONSE_LENGTH="${TACO_A9_MAX_RESPONSE_LENGTH:-2048}"
        export TACO_A9_MAX_MODEL_LENGTH="${TACO_A9_MAX_MODEL_LENGTH:-12288}"
        export TACO_A9_MAX_BATCHED_TOKENS="${TACO_A9_MAX_BATCHED_TOKENS:-12288}"
        export TACO_A9_MAX_NUM_SEQS="${TACO_A9_MAX_NUM_SEQS:-40}"
        export TACO_A9_VLLM_MEMORY_UTILIZATION="${TACO_A9_VLLM_MEMORY_UTILIZATION:-0.80}"
        export TACO_A9_VLLM_KV_CACHE_BYTES="${TACO_A9_VLLM_KV_CACHE_BYTES:-4294967296}"
        export TACO_A9_ACTOR_PARAM_OFFLOAD="${TACO_A9_ACTOR_PARAM_OFFLOAD:-true}"
        export TACO_A9_ACTOR_OPTIMIZER_OFFLOAD="${TACO_A9_ACTOR_OPTIMIZER_OFFLOAD:-true}"
        export TACO_A9_SAVE_FREQ="${TACO_A9_SAVE_FREQ:-50}"
        ;;
esac

pnp_launch_dataset "$DATASET" "$@"
